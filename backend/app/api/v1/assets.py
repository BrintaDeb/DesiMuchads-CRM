from fastapi import APIRouter, Depends, HTTPException, UploadFile, File, Query, status
from fastapi.responses import FileResponse
from pydantic import BaseModel
from typing import Optional
from app.services.s3_storage import storage_service
from app.core.security import get_current_user
from app.models.models import User
from app.schemas.schemas import ApiResponse
import mimetypes

router = APIRouter(prefix="/assets", tags=["Media & Brand Asset Storage"])


class PresignUploadRequest(BaseModel):
    filename: str
    content_type: str
    folder: Optional[str] = "media"


@router.post("/presign-upload", response_model=ApiResponse[dict])
async def get_presigned_upload_url(
    data: PresignUploadRequest,
    current_user: User = Depends(get_current_user),
):
    """
    Returns presigned URL configuration for direct asset upload.
    AWS S3 when configured; Local dev storage fallback otherwise.
    """
    res = storage_service.generate_presigned_upload_url(
        filename=data.filename,
        content_type=data.content_type,
        folder=data.folder or "media",
    )
    return ApiResponse(data=res)


@router.post("/upload", response_model=ApiResponse[dict])
async def upload_asset_direct(
    storage_key: str = Query(..., description="Unique storage path generated by presign step"),
    file: UploadFile = File(...),
):
    """
    Local storage upload fallback endpoint for dev and test environments.
    """
    content = await file.read()
    saved_path = storage_service.save_local_file(storage_key, content)
    file_url = f"/api/v1/assets/files/{storage_key}"
    return ApiResponse(
        data={
            "storage_key": storage_key,
            "file_url": file_url,
            "size_bytes": len(content),
            "filename": file.filename,
        }
    )


@router.get("/files/{storage_path:path}")
async def serve_stored_file(storage_path: str):
    """
    Serves stored assets in local development mode.
    """
    file_path = storage_service.get_local_file_path(storage_path)
    if not file_path:
        raise HTTPException(status_code=404, detail="File asset not found")

    content_type, _ = mimetypes.guess_type(file_path)
    return FileResponse(file_path, media_type=content_type or "application/octet-stream")

